// Verifies that every production dependency is under a license compatible
// with AGPL-3.0-only. Run with `--write` to also produce THIRD_PARTY_LICENSES.md.
//
// Usage: node scripts/check-licenses.mjs [--write]

import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

/** Licenses that may be combined into an AGPL-3.0-only work. */
const ALLOWED_EXACT = new Set([
  'MIT',
  'MIT-0',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'Apache-2.0',
  '0BSD',
  'CC0-1.0',
  'Unlicense',
  'MPL-2.0',
  'BlueOak-1.0.0',
  'Python-2.0',
  'CC-BY-4.0',
  'WTFPL',
  'Zlib',
]);
const ALLOWED_PREFIXES = ['LGPL-', 'GPL-3.0', 'AGPL-3.0'];

/** Packages that belong to this repo (no license check needed). */
const INTERNAL_PREFIX = '@ocpc/';

function isAllowedId(id) {
  const clean = id.trim().replace(/\+$/, '');
  if (ALLOWED_EXACT.has(clean)) return true;
  return ALLOWED_PREFIXES.some((p) => clean.startsWith(p));
}

/**
 * Evaluates a (simple) SPDX expression. OR → any alternative allowed;
 * AND → all parts allowed. Parentheses are supported.
 */
export function isAllowedExpression(expr) {
  if (!expr || typeof expr !== 'string') return false;
  const tokens = expr.replace(/\(/g, ' ( ').replace(/\)/g, ' ) ').split(/\s+/).filter(Boolean);
  let pos = 0;

  function parseOr() {
    let value = parseAnd();
    while (tokens[pos]?.toUpperCase() === 'OR') {
      pos++;
      const rhs = parseAnd();
      value = value || rhs;
    }
    return value;
  }
  function parseAnd() {
    let value = parseAtom();
    while (tokens[pos]?.toUpperCase() === 'AND') {
      pos++;
      const rhs = parseAtom();
      value = value && rhs;
    }
    return value;
  }
  function parseAtom() {
    const tok = tokens[pos++];
    if (tok === '(') {
      const v = parseOr();
      pos++; // ')'
      return v;
    }
    // "X WITH exception" — the exception only adds permissions.
    if (tokens[pos]?.toUpperCase() === 'WITH') pos += 2;
    return tok !== undefined && isAllowedId(tok);
  }

  try {
    const result = parseOr();
    return pos >= tokens.length && result;
  } catch {
    return false;
  }
}

function listLicenses() {
  const res = spawnSync('pnpm', ['licenses', 'list', '--json', '--prod'], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    shell: process.platform === 'win32',
  });
  if (res.status !== 0) {
    console.error(res.stderr || res.stdout);
    console.error('Failed to run `pnpm licenses list`. Did you run `pnpm install`?');
    process.exit(2);
  }
  const out = res.stdout.trim();
  if (!out || out.startsWith('No licenses')) return [];
  const data = JSON.parse(out);

  // pnpm groups packages by license: { "MIT": [{ name, versions, paths, ... }], ... }
  const pkgs = [];
  for (const [license, entries] of Object.entries(data)) {
    for (const entry of entries) {
      const versions = entry.versions ?? (entry.version ? [entry.version] : []);
      pkgs.push({
        name: entry.name,
        versions,
        license: entry.license ?? license,
        homepage: entry.homepage,
        author: entry.author,
        paths: entry.paths ?? (entry.path ? [entry.path] : []),
      });
    }
  }
  return pkgs.sort((a, b) => a.name.localeCompare(b.name));
}

function readLicenseText(paths) {
  for (const dir of paths) {
    if (!dir || !existsSync(dir)) continue;
    const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
    if (file) {
      try {
        return readFileSync(join(dir, file), 'utf8').trim();
      } catch {
        /* ignore */
      }
    }
  }
  return null;
}

function writeThirdParty(pkgs) {
  const lines = [
    '# Third-party licenses',
    '',
    'OpenCorpoChat includes the following third-party open-source packages.',
    'This file is generated by `pnpm licenses:check --write`; do not edit it by hand.',
    '',
    '| Package | Version(s) | License |',
    '|---|---|---|',
    ...pkgs.map((p) => `| ${p.name} | ${p.versions.join(', ')} | ${p.license} |`),
    '',
    '---',
    '',
  ];
  for (const p of pkgs) {
    lines.push(`## ${p.name} (${p.versions.join(', ')})`, '');
    lines.push(`License: ${p.license}`);
    if (p.homepage) lines.push(`Homepage: ${p.homepage}`);
    lines.push('');
    const text = readLicenseText(p.paths);
    if (text) lines.push('```text', text, '```', '');
  }
  writeFileSync('THIRD_PARTY_LICENSES.md', lines.join('\n'));
  console.log(`Wrote THIRD_PARTY_LICENSES.md (${pkgs.length} packages).`);
}

function main() {
  const write = process.argv.includes('--write');
  const pkgs = listLicenses().filter((p) => !p.name.startsWith(INTERNAL_PREFIX));
  const violations = pkgs.filter((p) => !isAllowedExpression(p.license));

  if (violations.length > 0) {
    console.error('Dependencies with licenses not on the AGPL-3.0-compatible allowlist:\n');
    for (const v of violations) {
      console.error(`  ✗ ${v.name}@${v.versions.join(',')}  — ${v.license || 'UNKNOWN'}`);
    }
    console.error(
      '\nReplace these dependencies, or (if the license is in fact compatible) add it to the',
      '\nallowlist in scripts/check-licenses.mjs in a PR reviewed by a maintainer.',
    );
    process.exit(1);
  }

  console.log(`✓ ${pkgs.length} production dependencies, all with AGPL-compatible licenses.`);
  if (write) writeThirdParty(pkgs);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
